def list_directory() -> tuple[list[str], list[str]]:
    """(screenshot names, non-PNG entries) in the screenshot directory."""
    path = os.path.join(REPO_ROOT, SHOT_DIR)
    if not os.path.isdir(path):
        die(f"{SHOT_DIR}/ does not exist")
    try:
        entries = sorted(os.listdir(path))
    except OSError as exc:
        die(f"cannot list {SHOT_DIR}/: {exc}")

    names = [e[:-4] for e in entries if e.endswith(".png")]
    extras = [e for e in entries if not e.endswith(".png")]
    return names, extras


def main(argv: list[str]) -> int:
    unknown = argv[1:]
    if unknown:
        sys.stderr.write(
            f"audit_screenshots: unknown argument(s): {' '.join(unknown)}\n"
        )
        sys.stderr.write(__doc__ or "")
        return 2

    desktop = parse_desktop_viewport(read_repo_text(CONFIG_PATH))
    shots = parse_spec(read_repo_text(SPEC_PATH), desktop)
    by_name = {shot.name: shot for shot in shots}

    on_disk, extras = list_directory()

    violations: list[Violation] = []
    violations += check_manifest(shots, on_disk, extras)

    stats: dict[str, Stats] = {}
    sizes: dict[str, int] = {}
    for name in on_disk:
        path = os.path.join(REPO_ROOT, SHOT_DIR, f"{name}.png")
        sizes[name] = os.path.getsize(path)
        file_violations, stat = check_file(name, path, by_name.get(name))
        violations += file_violations
        if stat is not None:
            stats[name] = stat

    violations += check_distinct(stats)
    documented_violations, references = check_documented(on_disk)
    violations += documented_violations

    print("Mathmon screenshot audit")
    print("========================")
    print(f"spec: {SPEC_PATH}   captures: {len(shots)}   on disk: {len(on_disk)}")
    print(
        f"desktop viewport from {CONFIG_PATH}: "
        f"{desktop[0]}x{desktop[1]} at {desktop[2]}x"
    )
    print()

    width = max([len(n) for n in on_disk] + [10])
    print(
        f"  {'screenshot'.ljust(width)}  {'pixels':>11}  {'KiB':>7}  {'colours':>7}  "
        f"{'top':>6}  {'white':>6}  {'lum':>6}  docs"
    )
    print(f"  {'-' * (width + 56)}")
    for name in on_disk:
        stat = stats.get(name)
        shot = by_name.get(name)
        where = ",".join(references.get(name, [])) or "-"
        if stat is None:
            print(f"  {name.ljust(width)}  {'unreadable':>11}")
            continue
        shot_size = (
            f"{shot.expected_px[0]}x{shot.expected_px[1]}" if shot else "no shot"
        )
        print(
            f"  {name.ljust(width)}  {shot_size:>11}  {sizes[name] / 1024:>7.0f}  "
            f"{stat.distinct_colours:>7}  {stat.dominant_share:>6.1%}  "
            f"{stat.light_share:>6.1%}  {stat.mean_luminance:>6.1f}  {where}"
        )
    print()
    print(
        "  top = share of the single most common colour, white = share of near-white"
    )
    print(
        "  pixels, lum = mean luminance. This app is dark on every screen, so a bright"
    )
    print("  row here is a crash page, not a screen.")

    unreferenced = sorted(set(on_disk) - set(references))
    if unreferenced:
        print()
        print("  Captured but embedded in no document (not a violation - a capture may")
        print("  exist purely as a record):")
        for name in unreferenced:
            print(f"    {SHOT_DIR}/{name}.png")

    print()
    if violations:
        print("FAIL")
        for prop, message in sorted(violations):
            print(f"  {prop}: {message}")
        properties = sorted({prop for prop, _ in violations})
        print()
        print(
            f"  {len(violations)} violation(s) across {len(properties)} propert(ies): "
            f"{', '.join(properties)}"
        )
        return 1

    print(
        "OK: P1 manifest, P2 decodable, P3 geometry, P4 legible, P5 distinct, "
        "P6 documented."
    )
    print()
    print("Scope note: this proves each screenshot is a real, distinct, correctly")
    print("sized, non-blank picture of a dark-themed screen. It cannot prove the")
    print("picture is of the screen its filename claims, or that it is current -")
    print("only re-running `npm run screenshots` does that.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
