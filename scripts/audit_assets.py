def _git(*args: str) -> list[str]:
    """Run a git command, failing loudly. Never pipe this through head/tail.

    A previous audit in this repository reported all-clear because its shell
    pipeline ended in `head`, and `head` exited 0 no matter what came before
    it. subprocess.run + an explicit returncode check is why that cannot
    happen here.
    """
    proc = subprocess.run(
        ["git", *args],
        cwd=REPO_ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(
            f"audit_assets: `git {' '.join(args)}` failed "
            f"({proc.returncode}): {proc.stderr.strip()}\n"
        )
        raise SystemExit(2)
    return [line for line in proc.stdout.split("\n") if line]


def collect_files() -> list[str]:
    """Tracked files plus untracked-but-not-ignored ones, sorted.

    Untracked files are included deliberately: a dropped .png should fail the
    audit the moment it lands in the working tree, not only once someone
    commits it. .gitignore is respected, which is what keeps node_modules/,
    .next/ and test-results/ out of the census.
    """
    tracked = _git("ls-files")
    untracked = _git("ls-files", "--others", "--exclude-standard")
    return sorted(set(tracked) | set(untracked))


def read_text(path: str) -> str | None:
    """Return decoded text, or None if the file is binary/unreadable."""
    try:
        with open(os.path.join(REPO_ROOT, path), "rb") as handle:
            raw = handle.read()
    except OSError:
        return None
    if b"\0" in raw:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return None


def size_of(path: str) -> int:
    try:
        return os.path.getsize(os.path.join(REPO_ROOT, path))
    except OSError:
        return 0


def is_doc(path: str) -> bool:
    return path.startswith(DOC_PATH_PREFIXES) or path.endswith(DOC_FILE_SUFFIXES)


# --------------------------------------------------------------------------
# Comment vs code
# --------------------------------------------------------------------------

_C_FAMILY = (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".swift", ".java")
_HASH_FAMILY = (".yml", ".yaml", ".py", ".sh", ".bash", ".toml", ".example")
_NO_COMMENT = (".json", ".webmanifest", ".lock")


def comment_style(path: str) -> str:
    base = os.path.basename(path)
    if base in (".gitignore", ".prettierignore", ".env.example", ".dockerignore"):
        return "hash"
    ext = os.path.splitext(path)[1].lower()
    if ext in _C_FAMILY:
        return "c"
    if ext == ".css":
        return "css"
    if ext in _HASH_FAMILY:
        return "hash"
    if ext in _NO_COMMENT:
        return "none"
    if ext in (".md", ".txt"):
        return "prose"
    return "none"


def comment_mask(text: str, style: str) -> list[bool]:
    """Per-character mask: True where the character sits inside a comment.

    This is a small state machine rather than a regex because the naive
    approach - "does the line contain // before the match" - classifies
    `const u = 'https://cdn.example.com/f.png'` as a comment, which would turn
    a real remote dependency into a silent pass. String literals are tracked,
    and `//` preceded by `:` is treated as a URL scheme, never a comment.
    """
    n = len(text)
    mask = [False] * n
    if style in ("none", "prose"):
        return mask

    if style == "c":
        line_tokens: tuple[str, ...] = ("//",)
        block: tuple[str, str] | None = ("/*", "*/")
        quotes = "'\"`"
    elif style == "css":
        line_tokens = ()
        block = ("/*", "*/")
        quotes = "'\""
    else:  # hash
        line_tokens = ("#",)
        block = None
        quotes = "'\""

    CODE, STRING, LINE_C, BLOCK_C = 0, 1, 2, 3
    state = CODE
    quote = ""
    i = 0
    while i < n:
        ch = text[i]
        if state == CODE:
            if ch in quotes:
                state, quote = STRING, ch
                i += 1
                continue
            if block is not None and text.startswith(block[0], i):
                state = BLOCK_C
                mask[i] = True
                if i + 1 < n:
                    mask[i + 1] = True
                i += 2
                continue
            opened = False
            for token in line_tokens:
                if not text.startswith(token, i):
                    continue
                if token == "//" and i > 0 and text[i - 1] == ":":
                    break  # URL scheme (https://), not a comment
                if token == "#" and i > 0 and text[i - 1] not in " \t\n":
                    break  # mid-token '#': a URL fragment or a colour literal
                state = LINE_C
                for k in range(i, min(i + len(token), n)):
                    mask[k] = True
                i += len(token)
                opened = True
                break
            if opened:
                continue
            i += 1
            continue

        if state == STRING:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                state = CODE
            i += 1
            continue

        if state == LINE_C:
            if ch == "\n":
                state = CODE
            else:
                mask[i] = True
            i += 1
            continue

        # BLOCK_C
        mask[i] = True
        if block is not None and text.startswith(block[1], i):
            if i + 1 < n:
                mask[i + 1] = True
            i += 2
            state = CODE
            continue
        i += 1
    return mask


def line_index(text: str) -> list[int]:
    starts = [0]
    for i, ch in enumerate(text):
        if ch == "\n":
            starts.append(i + 1)
    return starts


def locate(starts: list[int], offset: int) -> int:
    return bisect.bisect_right(starts, offset)


def excerpt_at(text: str, starts: list[int], lineno: int, limit: int = 140) -> str:
    start = starts[lineno - 1]
    end = text.find("\n", start)
    if end == -1:
        end = len(text)
    line = text[start:end].strip()
    return line if len(line) <= limit else line[: limit - 1] + "…"


