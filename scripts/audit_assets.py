# Check A - media files
# --------------------------------------------------------------------------


def check_media(files: list[str], report: Report) -> None:
    allowed_by_path = {a.path: a for a in MEDIA_ALLOWANCES}
    seen_allowances: set[str] = set()

    for path in files:
        ext = os.path.splitext(path)[1].lower()
        if ext not in MEDIA_EXTS:
            continue

        kind = "binary media" if ext in BINARY_MEDIA_EXTS else "vector media"
        size = size_of(path)

        if path.startswith(DOC_MEDIA_DIRS):
            report.note(
                "Documentation media (allowed - not shipped to a client)",
                Finding(path, 0, f"{kind}, {size:,} bytes"),
            )
            continue

        allowance = allowed_by_path.get(path)
        if allowance is not None:
            seen_allowances.add(path)
            problems = verify_allowance(allowance, size)
            if problems:
                for problem in problems:
                    report.violation(
                        "A. Allowlisted media file no longer meets its conditions",
                        Finding(path, 0, problem),
                    )
            else:
                report.note(
                    "Allowlisted media (reviewed exception, re-verified each run)",
                    Finding(
                        path,
                        0,
                        f"{kind}, {size:,} bytes (cap {allowance.max_bytes:,})",
                        allowance.reason,
                    ),
                )
            continue

        section = "A. Media asset committed outside the documentation directories"
        if path.startswith(SHIPPED_ASSET_DIRS):
            section = "A. Media asset in a SHIPPED directory"
        report.violation(
            section,
            Finding(
                path,
                0,
                f"{kind} ({ext}), {size:,} bytes. Allowed media locations are "
                + ", ".join(DOC_MEDIA_DIRS)
                + ". If this file is genuinely original and must ship, add a "
                "MEDIA_ALLOWANCES entry in scripts/audit_assets.py recording why.",
            ),
        )

    for allowance in MEDIA_ALLOWANCES:
        if allowance.path not in seen_allowances:
            # Not a failure: deleting an asset is the outcome this audit wants,
            # and it must never be the thing that breaks the build.
            report.note(
                "Stale allowlist entries (asset is gone - entry can be removed)",
                Finding(allowance.path, 0, "no such file in the repository"),
            )


def verify_allowance(allowance: MediaAllowance, size: int) -> list[str]:
    """Re-check an allowlisted asset. An allowance is a claim, not a bypass."""
    problems: list[str] = []
    if size > allowance.max_bytes:
        problems.append(
            f"grew to {size:,} bytes, over its {allowance.max_bytes:,} byte cap"
        )
    text = read_text(allowance.path)
    if text is None:
        problems.append("is not decodable text (an allowlisted vector must stay text)")
        return problems
    stripped = text.replace(SVG_NAMESPACE, "")
    for scheme in ("http://", "https://"):
        if scheme in stripped:
            problems.append(
                f"contains a {scheme} reference other than the SVG namespace, "
                "so it may fetch something at runtime"
            )
            break
    if "<image" in text.lower():
        problems.append("embeds a raster via <image>, defeating the point of a vector")
    if "@font-face" in text.lower() or "<font" in text.lower():
        problems.append("embeds a font")
    return problems


def check_shipped_dirs(files: list[str], report: Report) -> None:
    """Say explicitly what each shipped directory holds, present or absent."""
    for directory in SHIPPED_ASSET_DIRS:
        members = [f for f in files if f.startswith(directory)]
        if not members:
            report.note(
                "Shipped asset directories",
                Finding(
                    directory,
                    0,
                    "directory absent or empty - nothing shipped from here",
                ),
            )
            continue
        media = [f for f in members if os.path.splitext(f)[1].lower() in MEDIA_EXTS]
        total = sum(size_of(f) for f in members)
        allowed = {a.path for a in MEDIA_ALLOWANCES}
        unreviewed = sorted(set(media) - allowed)
        detail = (
            f"{len(members)} file(s), {total:,} bytes total; "
            f"{len(media)} media file(s), "
            f"{len(unreviewed)} of them unreviewed"
        )
        report.note("Shipped asset directories", Finding(directory, 0, detail))


# --------------------------------------------------------------------------
# Check B - remote asset references
# --------------------------------------------------------------------------


def check_remote_refs(files: list[str], report: Report) -> None:
    patterns = [
        (re.compile(p, re.IGNORECASE), label)
        for p, label in (*REMOTE_HOST_PATTERNS, *REMOTE_STRUCTURE_PATTERNS)
    ]
    css_patterns = [
        (re.compile(p, re.IGNORECASE), label) for p, label in REMOTE_CSS_PATTERNS
    ]

    for path in files:
        # Markdown and docs/ are prose about the project, not shipped source.
        # The Vercel deploy badge in README.md is a remote image, and that is
        # fine - it renders on GitHub, it is not part of the app.
        if is_doc(path):
            continue
        # This file necessarily contains the host list it searches for.
        if path == SELF_PATH:
            continue
        if os.path.splitext(path)[1].lower() in MEDIA_EXTS:
            continue

        text = read_text(path)
        if text is None:
            continue
        if path in LOCKFILES:
            continue

        mask = comment_mask(text, comment_style(path))
        starts = line_index(text)
        reported: set[tuple[int, str]] = set()

        # Spans of the SVG XML namespace. It is a URL, but it names a spec and
        # is never fetched; both renderers emit it on every drawing.
        ns_spans = [
            (m.start(), m.end())
            for m in re.finditer(re.escape(SVG_NAMESPACE), text)
        ]

        active = patterns
        if os.path.splitext(path)[1].lower() == ".css":
            active = patterns + css_patterns

        for regex, label in active:
            for match in regex.finditer(text):
                if any(s <= match.start() < e for s, e in ns_spans):
                    continue
                lineno = locate(starts, match.start())
                key = (lineno, label)
                if key in reported:
                    continue
                reported.add(key)
                in_comment = mask[match.start()]
                snippet = excerpt_at(text, starts, lineno)
                detail = f"{label}: {match.group(0)!r}"
                if in_comment:
                    report.note(
                        "B. Remote asset host named in a COMMENT (prose - allowed)",
                        Finding(path, lineno, detail, snippet),
                    )
                else:
                    report.violation(
                        "B. Remote asset host referenced in CODE",
                        Finding(
                            path,
                            lineno,
                            detail
                            + " - the app must fetch nothing at runtime; inline "
                            "or generate this instead",
                            snippet,
                        ),
                    )


