#!/usr/bin/env python3
"""Audit the "no third-party assets" claim that README.md and CLAUDE.md make.

Both files promise, in the user's own words, "non-copyrighted material":

    "The creatures are original. There are no Nintendo assets, names, or
     sprites anywhere in this repository, and there should never be."
    "No image, font, or audio assets ship with this app."

Until this script existed, nothing enforced that. A single dropped .png, a
`<link>` to fonts.googleapis.com, or a creature named after someone else's
would have falsified the claim silently. This turns it into an invariant that
CI checks on every push.

Four checks:

  A. Binary media committed anywhere outside the documentation directories.
  B. References to external asset hosts / remote font and image URLs, split
     into "in code" (a real dependency, fails) and "in a comment" (prose about
     a URL, reported but does not fail).
  C. Nintendo / Pokemon trademarked creature names in shipped source.
  D. A size census, so "the art is procedural geometry, not assets" is a
     number a reader can check rather than a sentence they have to trust.

Standard library only, no network, no clock, no randomness. Output is sorted
and byte-identical across runs, so a diff in CI output means a diff in the
repository.

Usage:
    python3 scripts/audit_assets.py            # audit; exit 1 on violation
    python3 scripts/audit_assets.py --quiet    # findings and totals only

Exit codes:  0 = clean   1 = violations found   2 = could not run the audit
"""

