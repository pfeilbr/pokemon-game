ART_GEOMETRY = ("src/lib/game/art.ts", "src/lib/game/creatures.ts")


def is_test(path: str) -> bool:
    base = os.path.basename(path)
    return ".test." in base or ".spec." in base or path.startswith("e2e/")


def size_census(files: list[str]) -> list[tuple[str, int, int]]:
    """(label, file count, bytes) rows. Sorted-input driven, so deterministic."""

    def total(paths: list[str]) -> tuple[int, int]:
        return len(paths), sum(size_of(p) for p in paths)

    web_src = [f for f in files if f.startswith("src/") and not is_test(f)]
    web_public = [f for f in files if f.startswith("public/")]
    mobile_src = [
        f
        for f in files
        if (f.startswith("mobile/src/") or f.startswith("mobile/assets/"))
        and not is_test(f)
    ]
    tests = [f for f in files if is_test(f)]
    doc_media = [f for f in files if f.startswith(DOC_MEDIA_DIRS)]
    art = [f for f in files if f in ART_GEOMETRY]

    rows = [
        ("Shared engine + web source (src/, excluding tests)", *total(web_src)),
        ("  of which creature art geometry (both clients)", *total(art)),
        ("Web shipped static dir (public/)", *total(web_public)),
        ("iOS client source (mobile/src, mobile/assets)", *total(mobile_src)),
        ("Tests (src/**/*.test.*, e2e/) - not shipped", *total(tests)),
        ("Documentation media - not shipped", *total(doc_media)),
        ("Everything tracked or untracked-not-ignored", *total(files)),
    ]
    return [(label, count, size) for label, count, size in rows]


