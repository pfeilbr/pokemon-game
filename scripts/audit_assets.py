# Check C - trademarked names
# --------------------------------------------------------------------------


def _word_regex(words: tuple[str, ...]) -> re.Pattern[str]:
    alts = sorted(words, key=len, reverse=True)
    return re.compile(
        r"(?<![0-9A-Za-z])(?:" + "|".join(re.escape(w) for w in alts) + r")(?![0-9A-Za-z])",
        re.IGNORECASE,
    )


def check_trademarks(files: list[str], report: Report) -> dict[str, int]:
    hard = _word_regex(TRADEMARK_TERMS + TRADEMARK_NAMES)
    ambiguous = _word_regex(AMBIGUOUS_TRADEMARK_NAMES)
    allowed = {(a.path, a.token.lower()) for a in NAME_ALLOWANCES}
    applied_allowances: set[tuple[str, str]] = set()
    masked_totals: dict[str, int] = {}

    for path in files:
        if is_doc(path):
            continue
        if path == SELF_PATH:
            continue
        if os.path.splitext(path)[1].lower() in MEDIA_EXTS:
            continue

        text = read_text(path)
        if text is None:
            continue

        if path in LOCKFILES:
            text = "\n".join(
                "" if LOCKFILE_NOISE_MARKER in line else line
                for line in text.split("\n")
            )

        # Mask the repository's own name before matching. Same-length
        # replacement keeps every offset valid, so line numbers stay honest.
        masked_count = len(REPO_SLUG_PATTERN.findall(text))
        if masked_count:
            masked_totals[path] = masked_count
            text = REPO_SLUG_PATTERN.sub(lambda m: "#" * len(m.group(0)), text)

        starts = line_index(text)
        mask = comment_mask(text, comment_style(path))

        for regex, section in (
            (hard, "C. Trademarked name in shipped source"),
            (
                ambiguous,
                "C. Trademarked name that is also an ordinary English word "
                "(confirm before renaming)",
            ),
        ):
            for match in regex.finditer(text):
                token = match.group(0).lower()
                if (path, token) in allowed:
                    applied_allowances.add((path, token))
                    continue
                lineno = locate(starts, match.start())
                where = "comment" if mask[match.start()] else "code"
                report.violation(
                    section,
                    Finding(
                        path,
                        lineno,
                        f"{match.group(0)!r} appears in {where}",
                        excerpt_at(text, starts, lineno),
                    ),
                )

    for allowance in NAME_ALLOWANCES:
        key = (allowance.path, allowance.token.lower())
        if key in applied_allowances:
            report.note(
                "Applied name exclusions (match found, permitted for a stated reason)",
                Finding(allowance.path, 0, f"{allowance.token!r}", allowance.reason),
            )
        else:
            report.note(
                "Stale allowlist entries (asset is gone - entry can be removed)",
                Finding(
                    allowance.path,
                    0,
                    f"{allowance.token!r} no longer appears here",
                ),
            )

    return masked_totals


