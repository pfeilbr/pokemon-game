def kib(n: int) -> str:
    return f"{n / 1024:.1f} KiB"


def render(report: Report, files: list[str], masked: dict[str, int], quiet: bool) -> str:
    out: list[str] = []
    add = out.append

    add("=" * 74)
    add("ASSET AND TRADEMARK AUDIT - Mathmon Battle League")
    add("=" * 74)
    add("")
    add(f"Files examined: {len(files)} (git-tracked plus untracked-not-ignored)")
    add("")

    if report.violations:
        add("-" * 74)
        add(f"VIOLATIONS ({report.violation_count})")
        add("-" * 74)
        for section in sorted(report.violations):
            findings = report.violations[section]
            add("")
            add(f"{section}  [{len(findings)}]")
            for finding in sorted(findings, key=lambda f: (f.path, f.line)):
                add(finding.render())
        add("")

    if not quiet:
        add("-" * 74)
        add("EXCLUSIONS APPLIED (and why)")
        add("-" * 74)
        add("")
        add("  Documentation is not scanned for trademarked names:")
        add("    README.md, CLAUDE.md, mobile/README.md, docs/**, mobile/docs/**")
        add("    These files legitimately describe what the project deliberately")
        add("    does NOT contain - README.md has a section titled 'A note on")
        add("    Pokemon' saying exactly that. Scanning them would make the audit")
        add("    fail for telling the truth.")
        add("")
        add("  The repository's own name is masked before matching:")
        add(f"    pattern {REPO_SLUG_PATTERN.pattern!r} (case-insensitive)")
        add("    The repo is called pokemon-game and the git remote URL embeds it,")
        add("    so the string appears unavoidably in Vercel import links and")
        add("    config. Masking is same-length, so line numbers stay correct.")
        if masked:
            for path in sorted(masked):
                add(f"      {masked[path]:3d} occurrence(s) masked in {path}")
        else:
            add("      (no occurrences outside documentation)")
        add("")
        add("  Lockfiles: `\"integrity\":` lines are skipped in " + ", ".join(LOCKFILES))
        add("    Those values are base64 digests and will contain arbitrary letter")
        add("    sequences by chance. Package names and resolved URLs are still")
        add("    scanned, so a dependency named after the franchise is still caught.")
        add("")
        add(f"  {SELF_PATH} is not scanned by checks B and C.")
        add("    It necessarily contains the very host list and name list it")
        add("    searches for. This is the audit's one blind spot; it is a single")
        add("    file, and it is reviewed like any other.")
        add("")
        add("  Markdown and docs/ are not scanned for remote asset hosts.")
        add("    The Vercel deploy badge in README.md is a remote image that")
        add("    renders on GitHub. It is documentation, not shipped app code.")
        add("")

        for section in sorted(report.notes):
            findings = report.notes[section]
            add("-" * 74)
            add(f"{section}  [{len(findings)}]")
            add("-" * 74)
            for finding in sorted(findings, key=lambda f: (f.path, f.line)):
                add(finding.render())
            add("")

    add("-" * 74)
    add("SIZE CENSUS - what actually ships")
    add("-" * 74)
    add("")
    add(f"  {'':52s}{'files':>7s}{'size':>13s}")
    for label, count, size in size_census(files):
        add(f"  {label:52s}{count:>7d}{kib(size):>13s}")
    add("")
    art_files = [f for f in files if f in ART_GEOMETRY]
    art_bytes = sum(size_of(f) for f in art_files)
    add(
        f"  All 36 creatures cost {kib(art_bytes)} of TypeScript geometry "
        f"({', '.join(ART_GEOMETRY)}),"
    )
    add("  shared verbatim by the web and iOS clients, and zero bytes of image")
    add("  assets. For comparison, the documentation screenshots - which no")
    add("  player ever downloads - are larger than the entire application.")
    add("")

    add("=" * 74)
    if report.failed:
        add(f"RESULT: FAIL - {report.violation_count} violation(s)")
        add("")
        add("The claim in README.md and CLAUDE.md that this repository ships no")
        add("third-party image, font or audio assets is currently FALSE.")
    else:
        add("RESULT: PASS")
        add("")
        add("No binary media outside the documentation directories, no remote")
        add("asset host referenced from code, and no trademarked creature name in")
        add("shipped source.")
    add("=" * 74)
    add("")
    add("Scope note: this audit proves the repository contains no third-party")
    add("*asset files* and fetches nothing at runtime. It cannot prove that")
    add("hand-written geometry is not a copy of someone else's drawing, and it")
    add("does not inspect node_modules. Those remain human judgements.")
    add("=" * 74)
    return "\n".join(out)


def main(argv: list[str]) -> int:
    quiet = "--quiet" in argv[1:]
    unknown = [a for a in argv[1:] if a not in ("--quiet",)]
    if unknown:
        sys.stderr.write(f"audit_assets: unknown argument(s): {' '.join(unknown)}\n")
        sys.stderr.write(__doc__ or "")
        return 2

    files = collect_files()
    report = Report()

    check_media(files, report)
    check_shipped_dirs(files, report)
    check_remote_refs(files, report)
    masked = check_trademarks(files, report)

    sys.stdout.write(render(report, files, masked, quiet) + "\n")
    return 1 if report.failed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
